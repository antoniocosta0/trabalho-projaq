-- Schema do Sistema de Gestao de Planos de Voo.
--
-- Precisa rodar do zero, em banco vazio, sem erro. Como o banco e H2 em
-- arquivo e o script roda a cada inicializacao, toda tabela usa
-- CREATE TABLE IF NOT EXISTS.
--
-- Checklist de modelagem: CONTEXT_NEW.md / CLAUDE.md, secao 14.3.
-- Quando entrarem as reservas, nao esquecer as duas restricoes de unicidade:
--
--   UNIQUE (aerovia_id, altitude, slot_inicio)
--   UNIQUE (aeroporto_codigo, numero_vaga, slot_inicio)

CREATE TABLE IF NOT EXISTS aeroporto (
    codigo            VARCHAR(10)  PRIMARY KEY,
    nome              VARCHAR(150) NOT NULL,
    quantidade_vagas  INT          NOT NULL CHECK (quantidade_vagas >= 0)
);

-- Aerovia nunca e alterada nem excluida (enunciado, secao 2).
CREATE TABLE IF NOT EXISTS aerovia (
    id              VARCHAR(20)      PRIMARY KEY,
    origem_codigo   VARCHAR(10)      NOT NULL REFERENCES aeroporto (codigo),
    destino_codigo  VARCHAR(10)      NOT NULL REFERENCES aeroporto (codigo),
    distancia_km    DOUBLE PRECISION NOT NULL CHECK (distancia_km > 0)
);

CREATE TABLE IF NOT EXISTS piloto (
    id    BIGINT       PRIMARY KEY,
    nome  VARCHAR(150) NOT NULL
);

-- Uma tabela para todas as categorias (estrategia "tabela unica").
CREATE TABLE IF NOT EXISTS aeronave (
    prefixo                  VARCHAR(10)      PRIMARY KEY,
    categoria                VARCHAR(20)      NOT NULL,
    velocidade_cruzeiro_kmh  DOUBLE PRECISION NOT NULL CHECK (velocidade_cruzeiro_kmh > 0),
    autonomia_km             DOUBLE PRECISION NOT NULL CHECK (autonomia_km > 0),
    empresa_manutencao       VARCHAR(150),
    companhia_aerea          VARCHAR(150),
    capacidade_passageiros   INT,
    capacidade_toneladas     DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS plano_de_voo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piloto_id         BIGINT      NOT NULL REFERENCES piloto (id),
    aeronave_prefixo  VARCHAR(10) NOT NULL REFERENCES aeronave (prefixo),
    origem_codigo     VARCHAR(10) NOT NULL REFERENCES aeroporto (codigo),
    destino_codigo    VARCHAR(10) NOT NULL REFERENCES aeroporto (codigo),
    partida           TIMESTAMP   NOT NULL,
    situacao          VARCHAR(20) NOT NULL
);
