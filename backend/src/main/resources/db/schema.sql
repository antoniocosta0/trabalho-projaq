-- Schema do Sistema de Gestao de Planos de Voo.
--
-- Precisa rodar do zero, em banco vazio, sem erro. Como o banco e H2 em
-- arquivo e o script roda a cada inicializacao, toda tabela usa
-- CREATE TABLE IF NOT EXISTS.
--
-- Checklist de modelagem: CONTEXT_NEW.md / CLAUDE.md, secao 14.3.
-- Reservas: os dois UNIQUE sao a ultima linha de defesa contra duas aprovacoes
-- simultaneas disputando a mesma altitude ou a mesma vaga no mesmo slot.

CREATE TABLE IF NOT EXISTS aeroporto (
    codigo            VARCHAR(10)  PRIMARY KEY,
    nome              VARCHAR(150) NOT NULL,
    quantidade_vagas  INT          NOT NULL CHECK (quantidade_vagas >= 0)
);

-- Aerovia nunca e alterada nem excluida (enunciado, secao 2).
CREATE TABLE IF NOT EXISTS aerovia (
    id              VARCHAR(20)      PRIMARY KEY,
    origem_codigo   VARCHAR(10)      NOT NULL REFERENCES aeroporto (codigo),
    destino_codigo  VARCHAR(10)      NOT NULL REFERENCES aeroporto (codigo),
    distancia_km    DOUBLE PRECISION NOT NULL CHECK (distancia_km > 0)
);

-- Id gerado pelo banco para o POST /pilotos. Comeca em 101 porque a carga
-- inicial informa os ids 1..4, e a identidade do H2 nao avanca com id informado.
CREATE TABLE IF NOT EXISTS piloto (
    id    BIGINT       GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
    nome  VARCHAR(150) NOT NULL
);

-- Uma tabela para todas as categorias (estrategia "tabela unica").
CREATE TABLE IF NOT EXISTS aeronave (
    prefixo                  VARCHAR(10)      PRIMARY KEY,
    categoria                VARCHAR(20)      NOT NULL,
    velocidade_cruzeiro_kmh  DOUBLE PRECISION NOT NULL CHECK (velocidade_cruzeiro_kmh > 0),
    autonomia_km             DOUBLE PRECISION NOT NULL CHECK (autonomia_km > 0),
    empresa_manutencao       VARCHAR(150),
    companhia_aerea          VARCHAR(150),
    capacidade_passageiros   INT,
    capacidade_toneladas     DOUBLE PRECISION
);

CREATE TABLE IF NOT EXISTS plano_de_voo (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    piloto_id         BIGINT      NOT NULL REFERENCES piloto (id),
    aeronave_prefixo  VARCHAR(10) NOT NULL REFERENCES aeronave (prefixo),
    origem_codigo     VARCHAR(10) NOT NULL REFERENCES aeroporto (codigo),
    destino_codigo    VARCHAR(10) NOT NULL REFERENCES aeroporto (codigo),
    partida           TIMESTAMP   NOT NULL,
    situacao          VARCHAR(20) NOT NULL
);

-- Percurso do plano. Pertence ao plano: sem identidade propria, a chave e
-- (plano, ordem). numero_vaga e permanencia_minutos nulos = sobrevoo.
CREATE TABLE IF NOT EXISTS trecho (
    plano_id             BIGINT      NOT NULL REFERENCES plano_de_voo (id),
    ordem                INT         NOT NULL,
    aerovia_id           VARCHAR(20) NOT NULL REFERENCES aerovia (id),
    altitude             INT         NOT NULL,
    horario_entrada      TIMESTAMP   NOT NULL,
    numero_vaga          INT,
    permanencia_minutos  INT,
    PRIMARY KEY (plano_id, ordem)
);

-- Uma linha por altitude e slot ocupados. Nasce so na aprovacao do plano e
-- some quando ele e cancelado (plano em edicao nunca tem reserva).
CREATE TABLE IF NOT EXISTS reserva_aerovia (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id     BIGINT      NOT NULL REFERENCES plano_de_voo (id),
    aerovia_id   VARCHAR(20) NOT NULL REFERENCES aerovia (id),
    altitude     INT         NOT NULL,
    slot_inicio  TIMESTAMP   NOT NULL,
    CONSTRAINT uq_reserva_aerovia UNIQUE (aerovia_id, altitude, slot_inicio)
);
CREATE INDEX IF NOT EXISTS ix_reserva_aerovia_plano ON reserva_aerovia (plano_id);

CREATE TABLE IF NOT EXISTS reserva_vaga (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id          BIGINT      NOT NULL REFERENCES plano_de_voo (id),
    aeroporto_codigo  VARCHAR(10) NOT NULL REFERENCES aeroporto (codigo),
    numero_vaga       INT         NOT NULL,
    slot_inicio       TIMESTAMP   NOT NULL,
    CONSTRAINT uq_reserva_vaga UNIQUE (aeroporto_codigo, numero_vaga, slot_inicio)
);
CREATE INDEX IF NOT EXISTS ix_reserva_vaga_plano ON reserva_vaga (plano_id);
